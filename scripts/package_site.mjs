import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const output = join(root, "dist");
const marker = join(output, ".generated_site");

// 手作業で置かれた同名フォルダを消さず、このコマンドの生成物だけを更新する。
if (existsSync(output) && !existsSync(marker)) {
  throw new Error("distが既にあります。中身を確認して別の場所へ移してから再実行してください。");
}
if (existsSync(output)) rmSync(output, { recursive: true });
mkdirSync(output, { recursive: true });
writeFileSync(marker, "Generated by npm run release. Do not edit files here.\n");

for (const entry of readdirSync(root, { withFileTypes: true })) {
  if (entry.isFile() && entry.name.endsWith(".html") && entry.name !== "firebase_seed.html") {
    cpSync(join(root, entry.name), join(output, entry.name));
  }
}
for (const folder of ["js", "images"]) {
  const target = join(output, "assets", folder);
  mkdirSync(target, { recursive: true });
  for (const entry of readdirSync(join(root, "assets", folder), { withFileTypes: true })) {
    if (
      !entry.isFile() ||
      entry.name.startsWith(".") ||
      entry.name === "firebase_seed.js" ||
      entry.name.endsWith("_prompt.txt")
    )
      continue;
    cpSync(join(root, "assets", folder, entry.name), join(target, entry.name));
  }
}
mkdirSync(join(output, "src", "scss"), { recursive: true });
cpSync(join(root, "src", "scss", "style.css"), join(output, "src", "scss", "style.css"));
console.log(
  "公開用ファイルをdistにまとめました。Cyberduckではdistの中身をアップロードしてください。",
);
